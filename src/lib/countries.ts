export type CountryCode = (typeof COUNTRY_CODES)[number]
type Locale = 'ar' | 'en'

const OVERRIDES: Partial<Record<CountryCode, Record<Locale, string>>> = {
  PS: { ar: 'فلسطين', en: 'Palestine' },
  XK: { ar: 'كوسوفو', en: 'Kosovo' },
}

const codes = new Set<string>(COUNTRY_CODES)
export const isCountryCode = (v: unknown): v is CountryCode => typeof v === 'string' && codes.has(v)

const names = new Map<Locale, Intl.DisplayNames>()
function displayNames(locale: Locale) {
  let d = names.get(locale)
  if (!d) {
    d = new Intl.DisplayNames([locale], { type: 'region', fallback: 'code' })
    names.set(locale, d)
  }
  return d
}

/** Localised country name; an unknown code comes back as itself, never as "Unknown Region". */
export function countryName(code: string, locale: Locale): string {
  if (!isCountryCode(code)) return code
  const o = OVERRIDES[code]
  if (o) return o[locale]
  try {
    return displayNames(locale).of(code) ?? code
  } catch {
    return code
  }
}

const sorted = new Map<Locale, { value: CountryCode; label: string }[]>()

/** `{ value, label }` pairs sorted by the localised name, memoised per locale. */
export function countryOptions(locale: Locale) {
  let list = sorted.get(locale)
  if (!list) {
    const collator = new Intl.Collator(locale)
    list = COUNTRY_CODES.map((value) => ({ value, label: countryName(value, locale) })).sort(
      (a, b) => collator.compare(a.label, b.label),
    )
    sorted.set(locale, list)
  }
  return list
}
